"""Generate src/yapyon/_wcwidth.py, the pinned display-width table (SPEC §14.1).

Usage:
    .venv/bin/python tools/gen_wcwidth_table.py [UCD_DIR]

With no argument, fetches the three files for the pinned version from
unicode.org; with one, reads them from UCD_DIR, named as unicode.org names
them (EastAsianWidth.txt, DerivedGeneralCategory.txt,
DerivedCoreProperties.txt) or with a -<version> suffix.

The table is two sets of sorted inclusive ranges:

    ZERO  width 0 -- General_Category Mn, Me, or Cf, or any other
          Default_Ignorable_Code_Point
    WIDE  width 2 -- East_Asian_Width W or F, and not in ZERO

Everything else is width 1. East_Asian_Width's defaults for code points the
file does not list are applied as the 14.0.0 file's own header states them:
N, except that *unassigned* code points (General_Category Cn) in the CJK
ideograph blocks and in Planes 2 and 3 default to W.

The pin is the identifier pin (`gen_xid_table.py`): changing it means
changing UNICODE_VERSION in both, re-running both, and reviewing the diff --
it is a change to the format, not a refresh.
"""

import sys
import urllib.request
from pathlib import Path

UNICODE_VERSION = "14.0.0"
BASE = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/"
FILES = {"eaw": "EastAsianWidth.txt",
         "gc": "extracted/DerivedGeneralCategory.txt",
         "dcp": "DerivedCoreProperties.txt"}
OUT = Path(__file__).resolve().parent.parent / "src" / "yapyon" / "_wcwidth.py"

# The 14.0.0 EastAsianWidth.txt header: unassigned code points here are W.
WIDE_UNASSIGNED = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
                   (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]


def fields(text: str):
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        rng, value = (f.strip() for f in line.split(";")[:2])
        lo, _, hi = rng.partition("..")
        yield int(lo, 16), int(hi or lo, 16), value


def collect(text: str, keep) -> set[int]:
    out = set()
    for lo, hi, value in fields(text):
        if keep(value):
            out.update(range(lo, hi + 1))
    return out


def ranges(points: set[int]) -> list[tuple[int, int]]:
    out: list[list[int]] = []
    for c in sorted(points):
        if out and c == out[-1][1] + 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return [(a, b) for a, b in out]


def render(name: str, rs: list[tuple[int, int]]) -> str:
    body = "".join(f"    (0x{a:04X}, 0x{b:04X}),\n" for a, b in rs)
    return f"{name} = (\n{body})\n"


def read(key: str, ucd: Path | None) -> str:
    name = FILES[key].rsplit("/", 1)[-1]
    if ucd is None:
        with urllib.request.urlopen(BASE + FILES[key]) as r:
            text = r.read().decode("utf-8")
    else:
        stem = name[:-4]
        candidates = [ucd / name, ucd / f"{stem}-{UNICODE_VERSION}.txt"]
        if key == "dcp":
            candidates.append(ucd / f"DCP-{UNICODE_VERSION}.txt")
        path = next((p for p in candidates if p.exists()), None)
        if path is None:
            raise SystemExit(f"no {name} for {UNICODE_VERSION} in {ucd}")
        text = path.read_text(encoding="utf-8")
    if f"{name[:-4]}-{UNICODE_VERSION}.txt" not in text[:300]:
        raise SystemExit(f"not the {UNICODE_VERSION} {name}")
    return text


def main(argv: list[str]) -> None:
    if len(argv) > 1 and argv[1] in ("-h", "--help"):
        print(__doc__)
        return
    ucd = Path(argv[1]) if len(argv) > 1 else None
    eaw, gc, dcp = (read(k, ucd) for k in ("eaw", "gc", "dcp"))

    zero = (collect(gc, lambda v: v in ("Mn", "Me", "Cf"))
            | collect(dcp, lambda v: v == "Default_Ignorable_Code_Point"))
    unassigned = collect(gc, lambda v: v == "Cn")
    listed = collect(eaw, lambda v: True)
    wide = collect(eaw, lambda v: v in ("W", "F"))
    for lo, hi in WIDE_UNASSIGNED:
        wide.update(c for c in range(lo, hi + 1)
                    if c in unassigned and c not in listed)
    wide -= zero

    OUT.write_text(
        '"""GENERATED by tools/gen_wcwidth_table.py -- do not edit.\n\n'
        f"Unicode {UNICODE_VERSION} display widths for SPEC §14.1, as sorted\n"
        "inclusive ranges: ZERO is width 0 (Mn, Me, Cf, and every other\n"
        "Default_Ignorable_Code_Point), WIDE is width 2 (East_Asian_Width W or\n"
        "F, not in ZERO). Every other code point is width 1.\n"
        f"{len(zero)} zero-width and {len(wide)} wide code points.\n"
        '"""\n\n'
        f'UNICODE_VERSION = "{UNICODE_VERSION}"\n\n'
        + render("ZERO", ranges(zero)) + "\n"
        + render("WIDE", ranges(wide)),
        encoding="utf-8")
    print(f"wrote {OUT}: {len(zero)} zero, {len(wide)} wide")


if __name__ == "__main__":
    main(sys.argv)
